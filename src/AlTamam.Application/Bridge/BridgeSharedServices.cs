    public async Task<BridgeResponse> ListSitesAsync(bool includeInactive, CancellationToken ct)
    {
        using var connection = _db.CreateOpenConnection();
        using var cmd = connection.CreateCommand();
        cmd.CommandText = includeInactive
            ? "SELECT SiteId, VisibleName, ActiveFlag, RowVersion FROM Sites ORDER BY VisibleName;"
            : "SELECT SiteId, VisibleName, ActiveFlag, RowVersion FROM Sites WHERE ActiveFlag = 1 ORDER BY VisibleName;";
        var sites = new JsonArray();
        using var reader = await cmd.ExecuteReaderAsync(ct).ConfigureAwait(false);
        while (await reader.ReadAsync(ct).ConfigureAwait(false))
            sites.Add(new JsonObject
            {
                ["siteId"] = reader.GetString(0),
                ["name"] = reader.GetString(1),
                ["active"] = Convert.ToInt32(reader.GetValue(2)) == 1,
                ["rowVersion"] = reader.GetInt64(3)
            });
        return Ok(sites);
    }

    public async Task<BridgeResponse> ListActiveStatusesAsync(CancellationToken ct)
    {
        using var connection = _db.CreateOpenConnection();
        using var cmd = connection.CreateCommand();
        cmd.CommandText = """
            SELECT s.StatusId,s.VisibleName,s.ShortSymbol,s.ChosenColorHex,
                   s.ActiveFlag,s.RowVersion,COALESCE(today.TodayCount,0)
            FROM AttendanceStatusDefinitions s
            LEFT JOIN (
                SELECT StatusId,COUNT(*) AS TodayCount FROM AttendanceRecords
                WHERE AttendanceLocalDate=$today GROUP BY StatusId
            ) today ON today.StatusId=s.StatusId
            WHERE s.ActiveFlag=1
            ORDER BY s.SortOrder,s.StatusId;
            """;
        cmd.Parameters.AddWithValue("$today",_time.GetLocalNow().ToString("yyyy-MM-dd"));
        var statuses = new JsonArray();
        using var reader = await cmd.ExecuteReaderAsync(ct).ConfigureAwait(false);
        while (await reader.ReadAsync(ct).ConfigureAwait(false))
            statuses.Add(new JsonObject
            {
                ["statusId"] = reader.GetString(0),
                ["displayName"] = reader.GetString(1),
                ["shortSymbol"] = reader.GetString(2),
                ["color"] = reader.GetString(3),
                ["active"] = Convert.ToInt32(reader.GetValue(4)) == 1,
                ["version"] = reader.GetInt64(5),
                ["todayCount"] = reader.GetInt64(6)
            });
        return Ok(statuses);
    }

    /// <summary>
    /// Search the current normalized identity, with an explicit active-only
    /// boundary for account pickers. Historical correction can still search
    /// departed persons by immutable PersonId without exposing them as eligible
    /// account targets. SQL LIKE metacharacters in user input are literal.
    /// </summary>
    public async Task<BridgeResponse> SearchPersonsAsync(string term, int take,
        CancellationToken ct, bool activeOnly = false)
    {
        if (string.IsNullOrWhiteSpace(term))
            return Error(BridgeErrorCodes.MissingData, "أدخل اسماً أو رقماً للبحث.");
        if (term.Length > 100 || term.Any(char.IsControl))
            return Error(BridgeErrorCodes.ValidationError,
                "بحث الأفراد لا يتجاوز 100 حرف ولا يقبل أحرف التحكم.");
        string normalized = ArabicTextNormalizer.NormalizeForSearch(term);
        if (normalized.Length == 0)
            return Error(BridgeErrorCodes.ValidationError,
                "أدخل اسماً أو رقماً صالحاً للبحث.");
        take = Math.Clamp(take <= 0 ? 25 : take, 1, 200);
        string like = "%" + normalized
            .Replace(@"\", @"\\", StringComparison.Ordinal)
            .Replace("%", @"\%", StringComparison.Ordinal)
            .Replace("_", @"\_", StringComparison.Ordinal) + "%";
        using var connection = _db.CreateOpenConnection();
        using var cmd = connection.CreateCommand();
        cmd.CommandText = """
            SELECT p.PersonId, p.CurrentVisibleName, p.CurrentServiceNumberA,
                   p.OrganizationalStatus, p.RowVersion,
                   COALESCE((SELECT s.VisibleName FROM PersonAssignments a
                             JOIN Sites s ON s.SiteId = a.SiteId
                             WHERE a.PersonId = p.PersonId
                               AND a.ValidToLocalDate IS NULL), 'غير محدد')
            FROM Persons p
            WHERE ($activeOnly = 0 OR (p.OrganizationalStatus = 1 AND p.ActiveFlag = 1))
              AND (p.NormalizedName LIKE $like ESCAPE '\'
                OR p.NormalizedServiceNumberA LIKE $like ESCAPE '\')
            ORDER BY p.CurrentVisibleName, p.PersonId LIMIT $take;
            """;
        cmd.Parameters.AddWithValue("$activeOnly", activeOnly ? 1 : 0);
        cmd.Parameters.AddWithValue("$like", like);
        cmd.Parameters.AddWithValue("$take", take);
        var rows = new JsonArray();
        using var reader = await cmd.ExecuteReaderAsync(ct).ConfigureAwait(false);
        while (await reader.ReadAsync(ct).ConfigureAwait(false))
            rows.Add(new JsonObject
            {
                ["personId"] = reader.GetString(0),
                ["displayName"] = reader.GetString(1),
                ["serviceNumberA"] = reader.GetString(2),
                ["organizationalStatus"] = reader.GetInt32(3),
                ["revision"] = reader.GetInt64(4),
                ["siteName"] = reader.GetString(5)
            });
        return Ok(new JsonObject { ["items"] = rows, ["count"] = rows.Count });
    }

    public async Task<BridgeResponse> ListDraftsAsync(string userId, CancellationToken ct)
    {
        using var connection = _db.CreateOpenConnection();
