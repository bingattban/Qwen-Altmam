/// <summary>
/// Shared, host-agnostic bridge services: provisioning detection, local authentication with server-side
/// session nonces, role-checked action authorization driven by the canonical manifest metadata, and the
/// Phase-04 basic data reads/writes used by the shared screens (sites, statuses, persons search, drafts).
/// Roles are resolved exclusively from the stored user row — a client-supplied role is never trusted.
/// </summary>
public sealed class BridgeSharedServices
{
    private readonly AlTamamDbContext _db;
    private readonly TimeProvider _time;
    // Nonces are generated by the server. Their in-memory cancellation signals
    // terminate outstanding bridge work as soon as Logout starts; the database
    // remains the durable authority and is checked on every session lookup.
    private readonly ConcurrentDictionary<string, CancellationTokenSource> _sessionTokens =
        new(StringComparer.Ordinal);
    private readonly ConcurrentDictionary<string, byte> _logoutStarted =
        new(StringComparer.Ordinal);
    public Func<string?,Task<string?>>? PickOutputDirectoryAsync { get; set; }
    public Func<string?,Task<string?>>? PickBackupFileAsync { get; set; }

    public BridgeSharedServices(AlTamamDbContext database, TimeProvider? timeProvider = null)
    {
        ArgumentNullException.ThrowIfNull(database);
        _db = database;
        _time = timeProvider ?? TimeProvider.System;
    }

    /// <summary>True if the database has EVER had an account: disabling users cannot reopen first-run setup.</summary>
    public async Task<bool> IsProvisionedAsync(CancellationToken cancellationToken = default)
    {
        using var connection = _db.CreateOpenConnection();
        return await FoundingProvisioningGuard.HasExistingEvidenceAsync(
            connection, null, cancellationToken).ConfigureAwait(false);
    }

    private static BridgeResponse? ValidateFoundingCredentials(
        string username, string password, string? founderFullName)
    {
        if (string.IsNullOrWhiteSpace(username) || username.Length is < 3 or > 64
            || username.Any(char.IsWhiteSpace))
            return Error(BridgeErrorCodes.ValidationError, "اسم المستخدم من 3 إلى 64 حرفاً بلا مسافات.");
        if (password is null || password.Length < 10)
            return Error(BridgeErrorCodes.ValidationError,
                "كلمة مرور حساب الإدارة العامة المؤسس لا تقل عن 10 خانات.");
        var strength = PasswordPolicyValidator.Validate(password);
        if (!strength.IsValid)
            return Error(BridgeErrorCodes.ValidationError,
                strength.ArabicErrorMessage ?? "كلمة المرور غير قوية.");
        if (founderFullName is not null && founderFullName.Trim().Length > 200)
            return Error(BridgeErrorCodes.ValidationError, "الاسم الكامل لصاحب حساب التأسيس طويل للغاية.");
        return null;
    }

    /// <summary>Creates the one user-chosen founding administrator, once per database.</summary>
    public async Task<BridgeResponse> ProvisionFirstAdministratorAsync(
        string username, string password, CancellationToken ct, string? founderFullName = null)
    {
        username = username?.Trim() ?? "";
        var invalid = ValidateFoundingCredentials(username, password, founderFullName);
        if (invalid is not null) return invalid;
        if (!await IsProvisionedAsync(ct).ConfigureAwait(false))
            return await CreateUserInternalAsync(username, password, UserRole.GeneralAdministration,
                requiresSetup: false, ct, founderFullName).ConfigureAwait(false);
        return Error(BridgeErrorCodes.ConflictStale,
            "تمت تهيئة البرنامج مسبقاً؛ لا يمكن إنشاء مدير أول آخر.");
    }

    /// <summary>
    /// Bootstrap ONLY: ordinary Admin/Supervisor accounts must be created through
    /// UserAccountManagementService with a verified permanent active roster link.
    /// Never expose a second way to create an unlinked or weak-credential user.
    /// </summary>
    public async Task<BridgeResponse> CreateUserInternalAsync(
        string username, string password, UserRole role, bool requiresSetup, CancellationToken ct,
        string? founderFullName = null)
    {
        if (role != UserRole.GeneralAdministration || requiresSetup)
            return Error(BridgeErrorCodes.Unauthorized,
                "الحساب المؤسس فقط يُنشأ دون ارتباط بكشف القوة؛ استخدم إدارة المستخدمين للحسابات الأخرى.");
        username = username?.Trim() ?? "";
        var invalid = ValidateFoundingCredentials(username, password, founderFullName);
        if (invalid is not null) return invalid;
        string normalized = NormalizeUsername(username);
        var (hash, salt) = PasswordSecurity.HashPassword(password);
        string userId = "USR-" + Guid.NewGuid().ToString("N");
        DateTimeOffset nowUtc = _time.GetUtcNow();
        return await _db.ExecuteInWriteTransactionAsync(async (connection, tx) =>
        {
            // Verify one-time founding authority inside the SAME serialized write
            // transaction. An existing disabled founder cannot be replaced.
            if (await FoundingProvisioningGuard.HasExistingEvidenceAsync(
                connection, tx, ct).ConfigureAwait(false))
                return Error(BridgeErrorCodes.ConflictStale,
                    "تمت تهيئة البرنامج مسبقاً؛ لا يمكن إنشاء مدير عام آخر.");
            using var dup = connection.CreateCommand();
            dup.Transaction = tx;
            dup.CommandText = "SELECT EXISTS(SELECT 1 FROM Users WHERE NormalizedUsername = $u);";
            dup.Parameters.AddWithValue("$u", normalized);
            if (Convert.ToInt32(await dup.ExecuteScalarAsync(ct).ConfigureAwait(false)) == 1)
                return Error(BridgeErrorCodes.DuplicateUsername, "اسم المستخدم مستخدم بالفعل.");
            using var insert = connection.CreateCommand();
            insert.Transaction = tx;
            insert.CommandText = @"INSERT INTO Users (UserId, LinkedPersonId, Username, NormalizedUsername, Role,
                                CredentialHash, PasswordSalt, RequiresFirstRunSetup, ActiveFlag, FailedLoginCount,
                                CreatedByUserId, CreatedByDisplaySnapshot, CreatedAtUtc, RowVersion,
                                FoundingFullName)
                                VALUES ($id, NULL, $name, $norm, $role, $hash, $salt, 0, 1, 0, 'USR-SYSTEM', 'النظام', $now, 1, $founder);";
            insert.Parameters.AddWithValue("$id", userId);
            insert.Parameters.AddWithValue("$name", username);
            insert.Parameters.AddWithValue("$norm", normalized);
            insert.Parameters.AddWithValue("$role", (int)role);
            insert.Parameters.AddWithValue("$hash", hash);
            insert.Parameters.AddWithValue("$salt", salt);
            insert.Parameters.AddWithValue("$now", nowUtc.ToString("O"));
            insert.Parameters.AddWithValue("$founder",
                string.IsNullOrWhiteSpace(founderFullName) ? DBNull.Value : founderFullName.Trim());
            await insert.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
            await BridgeAuditWriter.WriteAsync(connection, tx, _time,
                "FOUNDING_ADMIN_CREATED", "إنشاء الإدارة العامة عند التهيئة الأولى",
                userId, username, null, "User", userId, username,
                null, new JsonObject { ["role"] = "GeneralAdministration" }.ToJsonString(),
                "تهيئة الحساب المؤسس محلياً دون بيانات دخول افتراضية أو رقم (ع) وهمي",
                null, _time.GetLocalNow().ToString("yyyy-MM-dd"),
                Guid.NewGuid().ToString("N"), ct).ConfigureAwait(false);
            return Ok(new JsonObject { ["userId"] = userId, ["username"] = username,
                ["role"] = role.ToString() });
        }, ct).ConfigureAwait(false);
    }

    /// <summary>Authenticates against Argon2id hashes and issues a fresh random session nonce.</summary>
    public async Task<(BridgePrincipal? Principal, BridgeResponse? Failure)> AuthenticateAsync(
        string username, string password, CancellationToken ct)
    {
        if (string.IsNullOrWhiteSpace(username) || string.IsNullOrEmpty(password))
            return (null, Error(BridgeErrorCodes.ValidationError, "اسم المستخدم وكلمة المرور مطلوبان."));

        string normalized = NormalizeUsername(username);
        DateTimeOffset nowUtc = _time.GetUtcNow();
        return await _db.ExecuteInWriteTransactionAsync(async (connection, tx) =>
        {
            using var find = connection.CreateCommand();
            find.Transaction = tx;
            find.CommandText = """
                SELECT u.UserId,u.Username,u.Role,u.CredentialHash,u.PasswordSalt,
                       u.ActiveFlag,u.LockedUntilUtc,u.FailedLoginCount,
                       CASE WHEN u.Role=1 THEN 1
                            WHEN u.LinkedPersonId IS NOT NULL AND EXISTS(
                                SELECT 1 FROM Persons p
                                WHERE p.PersonId=u.LinkedPersonId AND p.ActiveFlag=1
                                  AND p.OrganizationalStatus=1) THEN 1
                            ELSE 0 END
                FROM Users u WHERE u.NormalizedUsername=$u;
                """;
            find.Parameters.AddWithValue("$u", normalized);
            using SqliteDataReader reader = await find.ExecuteReaderAsync(ct).ConfigureAwait(false);
            if (!await reader.ReadAsync(ct).ConfigureAwait(false))
                return ((BridgePrincipal?)null, Error(BridgeErrorCodes.Unauthorized, "بيانات الدخول غير صحيحة."));

            var userId = reader.GetString(0);
            var storedName = reader.GetString(1);
            var role = (UserRole)reader.GetInt32(2);
            var hash = reader.GetString(3);
            var salt = reader.GetString(4);
            bool active = Convert.ToInt32(reader.GetValue(5)) == 1;
            string? lockedUntil = reader.IsDBNull(6) ? null : reader.GetString(6);
            int failureCount = reader.GetInt32(7);
            bool eligibleForRoster = reader.GetInt32(8) == 1;
            reader.Close();

            if (!active)
                return (null, Error(BridgeErrorCodes.Unauthorized, "الحساب معطّل."));
            // Defense in depth for old/corrupt lifecycle state: personnel exit
            // must NEVER leave an active account or a reusable session behind.
            // Founder role remains separately governed to prevent accidental
            // permanent loss of the only GeneralAdmin (03.13 policy conflict).
            if (!eligibleForRoster)
            {
                using var suspend = connection.CreateCommand();
                suspend.Transaction = tx;
                suspend.CommandText = """
                    UPDATE Users SET ActiveFlag=0,RowVersion=RowVersion+1,
                        FailedLoginCount=0,LockedUntilUtc=NULL
                    WHERE UserId=$user AND Role<>1 AND ActiveFlag=1;
                    UPDATE UserSessions SET RevokedFlag=1
                    WHERE UserId=$user AND RevokedFlag=0;
                    """;
                suspend.Parameters.AddWithValue("$user",userId);
                await suspend.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
                await BridgeAuditWriter.WriteAsync(connection,tx,_time,
                    "USER_LIFECYCLE_SUSPEND_GUARD",
                    "تعطيل حساب لا يرتبط بفرد نشط في القوة",
                    "USR-SYSTEM","النظام","النظام","User",userId,storedName,
                    new JsonObject{["active"]=true}.ToJsonString(),
                    new JsonObject{["active"]=false,["reason"]="inactive-or-missing-roster"}.ToJsonString(),
                    "رفض تسجيل الدخول وإلغاء الجلسات بسبب انتهاء أهلية الفرد",
                    "اكتشاف حساب مرتبط بفرد غير نشط",
                    _time.GetLocalNow().ToString("yyyy-MM-dd"),
                    Guid.NewGuid().ToString("N"),ct).ConfigureAwait(false);
                return (null,Error(BridgeErrorCodes.Unauthorized,
                    "الفرد المرتبط بالحساب غير نشط؛ عُطّل الحساب ويلزم تفعيله مجدداً من الإدارة."));
            }
            if (lockedUntil is not null && DateTimeOffset.TryParse(lockedUntil, out DateTimeOffset lockEnd) && lockEnd > nowUtc)
                return (null, Error(BridgeErrorCodes.Unauthorized, "الحساب مقفل مؤقتاً بعد محاولات فاشلة متكررة."));

            if (!PasswordSecurity.VerifyPassword(password, hash, salt))
            {
                // Temporary lockouts are recoverable: once a 15-minute
                // cooldown expires the next wrong attempt starts at 1/5, not
                // an immediate new lock. Use injected TimeProvider instead
                // of SQLite's unrelated wall clock.
                bool cooldownPassed = lockedUntil is not null &&
                    DateTimeOffset.TryParse(lockedUntil,out DateTimeOffset lastLockEnd) &&
                    lastLockEnd <= nowUtc;
                int failures = cooldownPassed ? 1 : failureCount + 1;
                string? until = failures >= 5 ? nowUtc.AddMinutes(15).ToString("O") : null;
                using var fail = connection.CreateCommand();
                fail.Transaction = tx;
                fail.CommandText = """
                    UPDATE Users SET FailedLoginCount=$failures,
                        LockedUntilUtc=$until WHERE UserId=$id;
                    INSERT INTO FailedLoginEvents (UsernameAttempted,AttemptedAtUtc,FailureReason)
                    VALUES ($u,$now,'bad-password');
                    """;
                fail.Parameters.AddWithValue("$id",userId);
                fail.Parameters.AddWithValue("$u",normalized);
                fail.Parameters.AddWithValue("$now",nowUtc.ToString("O"));
                fail.Parameters.AddWithValue("$failures",failures);
                fail.Parameters.AddWithValue("$until",(object?)until ?? DBNull.Value);
                await fail.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
                await BridgeAuditWriter.WriteAsync(connection,tx,_time,
                    "AUTH_LOGIN_FAILED","محاولة دخول بكلمة مرور غير صحيحة",
                    userId,storedName,null,"User",userId,storedName,
                    new JsonObject{["failedAttempts"]=failureCount}.ToJsonString(),
                    new JsonObject{["failedAttempts"]=failures,["lockedUntilUtc"]=until}.ToJsonString(),
                    "لم يتم تسجيل الدخول","bad-password",
                    _time.GetLocalNow().ToString("yyyy-MM-dd"),
                    Guid.NewGuid().ToString("N"),ct).ConfigureAwait(false);
                return (null, Error(BridgeErrorCodes.Unauthorized, "بيانات الدخول غير صحيحة."));
            }

            // A second login cannot replace or preserve a currently signed-in
            // user's session. Log out explicitly, or let 300s inactivity expire.
            using(var existing=connection.CreateCommand())
            {
                existing.Transaction=tx;
                existing.CommandText="""
                    SELECT EXISTS(SELECT 1 FROM UserSessions
                      WHERE RevokedFlag=0 AND ExpiresAtUtc>$now);
                    """;
                existing.Parameters.AddWithValue("$now",nowUtc.ToString("O"));
                if(Convert.ToInt32(await existing.ExecuteScalarAsync(ct).ConfigureAwait(false))!=0)
                    return (null, Error(BridgeErrorCodes.Unauthorized,
                        "توجد جلسة مستخدم نشطة. لتغيير الحساب سجّل الخروج أولاً."));
            }
            string nonce = Convert.ToHexString(System.Security.Cryptography.RandomNumberGenerator.GetBytes(16));
            DateTimeOffset expiry = nowUtc.AddMinutes(5);
            using var session = connection.CreateCommand();
            session.Transaction = tx;
            session.CommandText = @"INSERT INTO UserSessions (SessionNonce, UserId, Role, IssuedAtUtc, ExpiresAtUtc, RevokedFlag)
                                    VALUES ($n, $id, $role, $now, $exp, 0);
                                    UPDATE Users SET FailedLoginCount = 0, LockedUntilUtc = NULL WHERE UserId = $id;";
            session.Parameters.AddWithValue("$n", nonce);
            session.Parameters.AddWithValue("$id", userId);
            session.Parameters.AddWithValue("$role", (int)role);
            session.Parameters.AddWithValue("$now", nowUtc.ToString("O"));
            session.Parameters.AddWithValue("$exp", expiry.ToString("O"));
            await session.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
            await BridgeAuditWriter.WriteAsync(connection,tx,_time,
                "AUTH_LOGIN_SUCCESS","تسجيل دخول ناجح",
                userId,storedName,null,"User",userId,storedName,
                null,new JsonObject{["role"]=role.ToString()}.ToJsonString(),
                "بدأت جلسة محلية مصرح بها دون حفظ رمز الجلسة أو كلمة المرور",
                null,_time.GetLocalNow().ToString("yyyy-MM-dd"),
                Guid.NewGuid().ToString("N"),ct).ConfigureAwait(false);

            return (new BridgePrincipal(userId, storedName, role, nonce), (BridgeResponse?)null);
        }, ct).ConfigureAwait(false);
    }

    /// <summary>Resolves a live nonce only while its saved role matches the current authorized user role.</summary>
    public async Task<BridgePrincipal?> ResolveSessionAsync(string sessionNonce, CancellationToken ct = default)
    {
        if (!BridgeProtocol.IsValidSessionNonceFormat(sessionNonce) ||
            _logoutStarted.ContainsKey(sessionNonce)) return null;
        using var connection = _db.CreateOpenConnection();
        using var cmd = connection.CreateCommand();
        cmd.CommandText = @"SELECT u.UserId, u.Username, s.Role
                            FROM UserSessions s JOIN Users u ON u.UserId = s.UserId
                            WHERE s.SessionNonce = $n AND s.RevokedFlag=0 AND s.ExpiresAtUtc>$now
                              AND u.ActiveFlag=1 AND s.Role=u.Role
                              AND (u.Role=1 OR (u.LinkedPersonId IS NOT NULL AND EXISTS(
                                  SELECT 1 FROM Persons p WHERE p.PersonId=u.LinkedPersonId
                                    AND p.ActiveFlag=1 AND p.OrganizationalStatus=1)));";
        cmd.Parameters.AddWithValue("$n", sessionNonce);
        cmd.Parameters.AddWithValue("$now", _time.GetUtcNow().ToString("O"));
        using var reader = await cmd.ExecuteReaderAsync(ct).ConfigureAwait(false);
        if (!await reader.ReadAsync(ct).ConfigureAwait(false)) return null;
        var lifetime = _sessionTokens.GetOrAdd(
            sessionNonce, _ => new CancellationTokenSource());
        // Handles logout racing with the database read or with GetOrAdd.
        if (_logoutStarted.ContainsKey(sessionNonce)) lifetime.Cancel();
        if (lifetime.IsCancellationRequested) return null;
        return new BridgePrincipal(
            reader.GetString(0), reader.GetString(1),
            (UserRole)reader.GetInt32(2), sessionNonce)
        {
            SessionRevocation = lifetime.Token
        };
    }

    /// <summary>
    /// Renew the server-side five-minute idle deadline only after a real UI activity
    /// heartbeat. Ordinary background queries do not extend the session.
    /// Expired sessions cannot be revived by reusing an old nonce.
    /// </summary>
    public async Task RefreshSessionIdleDeadlineAsync(string nonce,CancellationToken ct=default)
    {
        if(!BridgeProtocol.IsValidSessionNonceFormat(nonce))return;
        using var c=_db.CreateOpenConnection();
        using var cmd=c.CreateCommand();
        cmd.CommandText="""
            UPDATE UserSessions SET ExpiresAtUtc=$newExpiry
            WHERE SessionNonce=$nonce AND RevokedFlag=0 AND ExpiresAtUtc>$now
              AND EXISTS(SELECT 1 FROM Users u WHERE u.UserId=UserSessions.UserId
                AND u.ActiveFlag=1 AND u.Role=UserSessions.Role AND (u.Role=1 OR
                (u.LinkedPersonId IS NOT NULL AND EXISTS(
                  SELECT 1 FROM Persons p WHERE p.PersonId=u.LinkedPersonId
                    AND p.ActiveFlag=1 AND p.OrganizationalStatus=1))));
            """;
        cmd.Parameters.AddWithValue("$nonce",nonce);
        cmd.Parameters.AddWithValue("$now",_time.GetUtcNow().ToString("O"));
        cmd.Parameters.AddWithValue("$newExpiry",_time.GetUtcNow().AddMinutes(5).ToString("O"));
        await cmd.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
    }

    /// <summary>
    /// A restarted desktop process has no still-authenticated human UI session.
    /// Revoke any orphaned nonces from its previous run BEFORE accepting logins.
    /// </summary>
    public async Task RevokeOrphanedSessionsOnStartupAsync(CancellationToken ct=default)
    {
        using var c=_db.CreateOpenConnection();
        using var q=c.CreateCommand();
        q.CommandText="UPDATE UserSessions SET RevokedFlag=1 WHERE RevokedFlag=0;";
        await q.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
    }

    /// <summary>
    /// Only WPF-hosted, genuine native input handlers call this; background
    /// schedulers, UI counters, and polling never invoke it.
    /// </summary>
    public async Task RefreshActiveSessionFromNativeInputAsync(CancellationToken ct=default)
    {
        using var c=_db.CreateOpenConnection();
        using var q=c.CreateCommand();
        q.CommandText="""
            UPDATE UserSessions SET ExpiresAtUtc=$deadline
            WHERE RevokedFlag=0 AND ExpiresAtUtc>$now
              AND EXISTS(SELECT 1 FROM Users u WHERE u.UserId=UserSessions.UserId
                AND u.ActiveFlag=1 AND u.Role=UserSessions.Role AND (u.Role=1 OR
                (u.LinkedPersonId IS NOT NULL AND EXISTS(
                  SELECT 1 FROM Persons p WHERE p.PersonId=u.LinkedPersonId
                    AND p.ActiveFlag=1 AND p.OrganizationalStatus=1))));
            """;
        q.Parameters.AddWithValue("$now",_time.GetUtcNow().ToString("O"));
        q.Parameters.AddWithValue("$deadline",_time.GetUtcNow().AddSeconds(300).ToString("O"));
        await q.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
    }

    /// <summary>Revokes the presenting session (Logout / SessionEnded).</summary>
    public async Task RevokeSessionAsync(string sessionNonce, CancellationToken ct = default)
    {
        // Mark the nonce unusable and cancel in-flight requests BEFORE waiting
        // for the SQLCipher write lock; otherwise a slow operation can finish
        // after the user explicitly logs out.
        if (BridgeProtocol.IsValidSessionNonceFormat(sessionNonce))
        {
            _logoutStarted.TryAdd(sessionNonce, 0);
            if (_sessionTokens.TryGetValue(sessionNonce, out var lifetime))
                lifetime.Cancel();
        }
        await _db.ExecuteInWriteTransactionAsync(async (connection, tx) =>
        {
            string? userId=null,username=null;
            using(var user=connection.CreateCommand())
            {
                user.Transaction=tx;
                user.CommandText="""
                    SELECT u.UserId,u.Username FROM UserSessions s
                    JOIN Users u ON u.UserId=s.UserId
                    WHERE s.SessionNonce=$n AND s.RevokedFlag=0;
                    """;
                user.Parameters.AddWithValue("$n",sessionNonce);
                using var row=await user.ExecuteReaderAsync(ct).ConfigureAwait(false);
                if(await row.ReadAsync(ct).ConfigureAwait(false))
                {
                    userId=row.GetString(0);
                    username=row.GetString(1);
                }
            }
            using var cmd = connection.CreateCommand();
            cmd.Transaction = tx;
            cmd.CommandText = "UPDATE UserSessions SET RevokedFlag = 1 WHERE SessionNonce = $n AND RevokedFlag=0;";
            cmd.Parameters.AddWithValue("$n", sessionNonce);
            int changed=await cmd.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
            if(changed>0 && userId is not null && username is not null)
                await BridgeAuditWriter.WriteAsync(connection,tx,_time,
                    "AUTH_LOGOUT","تسجيل خروج وإلغاء صلاحية الجلسة",
                    userId,username,null,"User",userId,username,
                    new JsonObject{["sessionActive"]=true}.ToJsonString(),
                    new JsonObject{["sessionActive"]=false}.ToJsonString(),
                    "أُلغيت صلاحية الجلسة دون تسجيل رمز الجلسة",
                    null,_time.GetLocalNow().ToString("yyyy-MM-dd"),
                    Guid.NewGuid().ToString("N"),ct).ConfigureAwait(false);
            return 0;
        }, ct).ConfigureAwait(false);
    }

